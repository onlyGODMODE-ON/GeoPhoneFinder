export function specsFor(m) {
  const [size, w, h, hz, panel, nits, hdr] = m.d;
  const [mah, wired, wireless] = m.b;
  const [maxRes, max4kFps, videoHdr, frontRes] = m.v;
  const [wifi, bluetooth, nfc, esim, usb] = m.n;
  const [ip, glass, frame] = [m.body[2], m.body[3], m.body[4]];
  return {
    chipsetName: m.chipset,
    fiveG: m.fiveG,
    display: { sizeInch: size, resolution: { width: w, height: h }, refreshRateHz: hz, panel, peakBrightnessNits: nits, hdr },
    battery: { capacityMah: mah, wiredW: wired, wirelessW: wireless },
    cameras: m.c,
    video: { maxResolution: maxRes, max4kFps, hdr: videoHdr, frontMaxResolution: frontRes },
    connectivity: { fiveG: m.fiveG, wifi, bluetooth, nfc, esim, usb },
    audio: { stereo: m.a[0], tuned: m.a[1] },
    body: { weightG: m.body[0], thicknessMm: m.body[1], ipRating: ip, glass, frame },
    software: { os: m.sw[0], osUpdateYears: m.sw[1], securityUpdateYears: m.sw[2] },
    benchmarks: null, // sustained-performance / thermal / endurance data: not available => excluded from scores
  };
}


