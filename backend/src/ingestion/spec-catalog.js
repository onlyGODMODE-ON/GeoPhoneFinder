// MORE_MODELS carry a price per variant: variants: [[ram, storage, priceGEL], ...]. The catalog keeps [ram, storage] pairs.
export const SPEC_CATALOG = [...MODELS, ...MORE_MODELS].map((m) => ({
  ...m,
  variants: m.variants.map(([ram, storage]) => [ram, storage]),
  colors: COLORS[m.key] ?? DEFAULT_COLORS[m.brand] ?? [],
}));

/** Base (Zoommer) price rows [modelKey, ram, storage, priceGEL] for the models that ship with prices. */
export const MORE_PRICE_ROWS = MORE_MODELS.flatMap((m) => m.variants.map(([ram, storage, price]) => [m.key, ram, storage, price]));

const INDEX = new Map(SPEC_CATALOG.map((m) => [`${keyOf(m.brand)}|${keyOf(m.model)}`, m]));

/** Catalog entry for a normalised (brand, model), or null. */
export function findCatalogModel(brand, model) {
  return INDEX.get(`${keyOf(brand)}|${keyOf(model)}`) ?? null;
}

/** Specs to merge into a listing that lacks them, or null when the model is not in the catalog. */
export function lookupSpecs(brand, model) {
  const m = findCatalogModel(brand, model);
  return m ? specsFor(m) : null;
}
